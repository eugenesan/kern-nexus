#!/usr/bin/env python3
"""Generate tools/sighash/vectors.c from the embit unified-sighash vectors."""
import json
import sys
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else
           "/home/user/Develop/src/krux-nexus/krux/vendor/embit/tests/tests/data/unified_sighash.json")
out = Path(__file__).with_name("vectors.c")
data = json.loads(src.read_text())
header, rows = data[0], data[1:]
assert header == ["scriptCode", "rawTx", "inIdx", "hashType", "scriptType",
                  "spentOutputs", "sighash"]
max_spent = max(4, max(len(r[5]) for r in rows))
lines = [
    "/* generated by gen_vectors.py from embit unified_sighash.json */",
    "#include <stdint.h>",
    "#include <stddef.h>",
    "struct tvec_spent { uint64_t value; const char *script; };",
    "struct tvec { const char *script_code; const char *rawtx;",
    "  unsigned in_idx, hash_type, script_type; size_t nspent;",
    f"  struct tvec_spent spent[{max_spent}]; const char *expected; }};",
    "const struct tvec tvecs[] = {",
]
for row in rows:
    sc, raw, idx, ht, st, spent, expected = row
    parts = ", ".join('{%du, "%s"}' % (int(v), s) for v, s in spent)
    parts += ", {0, 0}" * (max_spent - len(spent))
    lines.append('  {"%s", "%s", %d, %d, %d, %d, {%s}, "%s"},' %
                 (sc, raw, idx, ht, st, len(spent), parts, expected))
lines += ["};",
          "const size_t tvec_count = sizeof(tvecs) / sizeof(tvecs[0]);",
          ""]
out.write_text("\n".join(lines))
print("wrote", out, len(rows), "vectors, max spent", max_spent)
